// Generate metadata and Python wrappers for the explicitly reviewed synchronous subset.
// The descriptor is not a security boundary or an automatic binding to native code.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
const descriptor = path.join(root, 'src/dualWasmProbe/sync-api.json')
const apiDir = process.env.VSP_API_DIR ?? path.resolve(root, '../../src/geom_api')
const header = await readFile(path.join(apiDir, 'VSP_Geom_API.h'), 'utf8')
const swig = await readFile(path.join(apiDir, 'vsp_common.i'), 'utf8')
if (!swig.includes('%include "VSP_Geom_API.h"')) throw new Error('SWIG header inclusion changed')
const doc = JSON.parse(await readFile(descriptor, 'utf8'))
if (doc.version !== 3 || !Array.isArray(doc.apis) || !doc.apis.length) throw new Error('Invalid descriptor version or API list')
const names = new Set(), ops = new Set()
const ident = /^[A-Za-z_][A-Za-z0-9_]*$/
const reserved = new Set(['False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif', 'else', 'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or', 'pass', 'raise', 'return', 'try', 'while', 'with', 'yield'])
const pythonIdent = (value) => typeof value === 'string' && ident.test(value) && !reserved.has(value)
const normalize = (s) => s.replace(/\s+/g, ' ').trim()
const pyValue = (v) => typeof v === 'boolean' ? (v ? 'True' : 'False') : JSON.stringify(v)
for (const a of doc.apis) {
  if (!pythonIdent(a.name) || !/^[a-z][a-z0-9_]*$/.test(a.operation) || names.has(a.name) || ops.has(a.operation)) throw new Error('Invalid or duplicate API name/operation')
  names.add(a.name); ops.add(a.operation)
  if (a.status !== 'experimental' || typeof a.write !== 'boolean' || !['model_check', 'guarded_read', 'guarded_write'].includes(a.epoch) || (a.write !== (a.epoch === 'guarded_write'))) throw new Error(`Invalid guard metadata for ${a.name}`)
  if (!['string', 'string_array', 'number', 'integer', 'number_array', 'string_array', 'matrix', 'vec3d_array', 'null'].includes(a.returns) || !a.scope || !a.errors || !Array.isArray(a.tests) || !a.tests.length || !Array.isArray(a.arguments)) throw new Error(`Incomplete API metadata for ${a.name}`)
  const declarations = [...header.matchAll(new RegExp(`\\bextern\\s+[^;{}]*\\b${a.nativeName ?? a.name}\\s*\\([^;{}]*\\)\\s*;`, 'g'))].map((m) => normalize(m[0]))
  const diagnosticOnly = typeof a.native === 'string' && a.native.startsWith('diagnostic-only ')
  if (!diagnosticOnly && declarations.filter((v) => v === normalize(a.native)).length !== 1) throw new Error(`Reviewed native overload missing or changed: ${a.name}`)
  if (diagnosticOnly && !a.native.startsWith('diagnostic-only ')) throw new Error(`Invalid diagnostic-only declaration for ${a.name}`)
  const args = new Set(), wires = new Set(); let hasDefault = false
  for (const arg of a.arguments) {
    if (!pythonIdent(arg.name) || !pythonIdent(arg.wire) || args.has(arg.name) || wires.has(arg.wire) || !['string', 'number', 'integer', 'boolean'].includes(arg.type)) throw new Error(`Invalid argument in ${a.name}`)
    args.add(arg.name); wires.add(arg.wire)
    if ('default' in arg) {
      hasDefault = true
      if (!((arg.type === 'string' && typeof arg.default === 'string') || (arg.type === 'boolean' && typeof arg.default === 'boolean') || (['integer', 'number'].includes(arg.type) && typeof arg.default === 'number' && Number.isFinite(arg.default)))) throw new Error(`Invalid default in ${a.name}`)
    } else if (hasDefault) throw new Error(`Required argument follows default in ${a.name}`)
  }
}
const python = [
  '# Generated by scripts/generate-sync-api.mjs; do not edit.',
  '# Restricted synchronous diagnostic API; see sync-api.json.',
  'from openvsp import _call', '',
  ...doc.apis.flatMap((a) => [
    `def ${a.name}(${a.arguments.map((arg) => arg.name + ('default' in arg ? `=${pyValue(arg.default)}` : '')).join(', ')}):`,
    `    return _call('${a.operation}'${a.arguments.map((arg) => `, ${arg.wire}=${arg.name}`).join('')})`, '', '',
  ]),
  `_WRITE_OPERATIONS = frozenset(${JSON.stringify(doc.apis.filter((a) => a.write).map((a) => a.operation))})`, '',
].join('\n')
const ts = `// Generated by scripts/generate-sync-api.mjs; do not edit.\nexport const SYNC_API = ${JSON.stringify(doc.apis.map(({ name, operation, arguments: args, returns, write, epoch }) => ({ name, operation, arguments: args.map(({ wire, type }) => ({ wire, type })), returns, write, epoch })), null, 2)} as const\n`
const table = ['<!-- Generated by scripts/generate-sync-api.mjs; do not edit. -->', '# Reviewed synchronous API inventory', '', '| API | Operation | Result | Write | Guard | Scope | Errors | Tests |', '| --- | --- | --- | --- | --- | --- | --- | --- |', ...doc.apis.map((a) => `| \`${a.name}\` | \`${a.operation}\` | ${a.returns} | ${a.write ? 'yes' : 'no'} | ${a.epoch} | ${a.scope} | ${a.errors} | ${a.tests.join(', ')} |`), '', 'This inventory is restricted to existing fixed diagnostics. It does not imply native behavioral parity or expose additional operations.', ''].join('\n')
const outputs = [[path.join(root, 'src/dualWasmProbe/python/_sync_generated.py'), python], [path.join(root, 'src/dualWasmProbe/syncApi.generated.ts'), ts], [path.join(root, 'src/dualWasmProbe/SYNC_API.md'), table]]
const check = process.argv.length === 3 && process.argv[2] === '--check'
if (!check && process.argv.length !== 2) throw new Error('Usage: node scripts/generate-sync-api.mjs [--check]')
for (const [file, content] of outputs) {
  if (check) {
    if (await readFile(file, 'utf8') !== content) throw new Error(`Generated output is stale: ${file}`)
  } else await writeFile(file, content)
}
console.log(check ? 'Synchronous API inventory and generated outputs match' : 'Generated synchronous API outputs')
