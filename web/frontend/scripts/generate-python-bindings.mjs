// Generate only reviewed bridge operations; native declarations are validation inputs, not an API allowlist.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const frontend = fileURLToPath(new URL('..', import.meta.url))
const apiDir = process.env.VSP_API_DIR ?? path.resolve(frontend, '../../src/geom_api')
const output = path.join(frontend, 'src/dualWasmProbe/python/openvsp_wasm/_generated.py')
const declarations = await readFile(path.join(apiDir, 'VSP_Geom_API.h'), 'utf8')
const defines = await readFile(path.join(apiDir, 'APIDefines.h'), 'utf8')
const swig = await readFile(path.join(apiDir, 'vsp_common.i'), 'utf8')
for (const name of ['VSP_Geom_API.h', 'APIDefines.h']) {
  if (!swig.includes(`%include "${name}"`)) throw new Error(`SWIG no longer includes ${name}`)
}

// Exact reviewed C++ signatures, Python spelling, and bridge argument mappings.
// The engine implements a deliberately narrower subset than the native API.
const functions = [
  { name: 'FindGeoms', declaration: 'extern std::vector<std::string> FindGeoms();', args: '', op: 'find_geoms', mapped: '' },
  { name: 'GetGeomName', declaration: 'extern std::string GetGeomName( const std::string & geom_id );', args: 'geom_id', op: 'geom_name', mapped: ', geom_id=geom_id' },
  { name: 'GetGeomTypeName', declaration: 'extern std::string GetGeomTypeName( const std::string & geom_id );', args: 'geom_id', op: 'geom_type', mapped: ', geom_id=geom_id' },
  { name: 'AddGeom', declaration: 'extern std::string AddGeom( const std::string & type, const std::string & parent = std::string() );', args: "type, parent=''", op: 'add_geom', mapped: ', geom_type=type, parent=parent' },
  { name: 'GetGeomParmIDs', declaration: 'extern std::vector<std::string> GetGeomParmIDs( const std::string & geom_id );', args: 'geom_id', op: 'parm_ids', mapped: ', geom_id=geom_id' },
]
for (const entry of functions) {
  const escaped = entry.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const matches = [...declarations.matchAll(new RegExp(`\\bextern\\s+[^;{}]*\\b${escaped}\\s*\\([^;{}]*\\)\\s*;`, 'g'))]
  const normalize = (text) => text.replace(/\s+/g, ' ').trim()
  if (matches.length !== 1 || normalize(matches[0][0]) !== normalize(entry.declaration)) throw new Error(`Native declaration changed or overloaded: ${entry.name}`)
}

const enumMatches = [...defines.matchAll(/\benum\s+PARM_TYPE\s*\{([^}]+)\}\s*;/g)]
if (enumMatches.length !== 1) throw new Error('Expected exactly one PARM_TYPE enum')
const cleaned = enumMatches[0][1].replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
const names = cleaned.split(',').map((s) => s.trim()).filter(Boolean)
const expected = ['PARM_DOUBLE_TYPE', 'PARM_INT_TYPE', 'PARM_BOOL_TYPE', 'PARM_FRACTION_TYPE', 'PARM_LIMITED_INT_TYPE', 'PARM_NOTEQ_TYPE', 'PARM_POWER_INT_TYPE']
if (JSON.stringify(names) !== JSON.stringify(expected)) throw new Error('PARM_TYPE changed; review its values and update the generator')
const result = [
  '# Generated by scripts/generate-python-bindings.mjs; do not edit.',
  '# Source: src/geom_api/VSP_Geom_API.h and APIDefines.h; reviewed subset only.',
  'from . import _call',
  '',
  ...names.map((name, index) => `${name} = ${index}`),
  '',
  ...functions.flatMap(({ name, args, op, mapped }) => [
    `async def ${name}(${args}):`,
    `    """Asynchronous limited bridge for native ${name}; see compatibility notes."""`,
    `    return await _call('${op}'${mapped})`,
    '',
    '',
  ]),
  `__all__ = ${JSON.stringify([...names, ...functions.map((entry) => entry.name)])}`,
  '',
].join('\n')
if (process.argv.slice(2).join(' ') === '--check') {
  if (await readFile(output, 'utf8') !== result) throw new Error('Generated Python bindings are stale; run node scripts/generate-python-bindings.mjs')
  console.log('Generated Python bindings match native declarations')
} else if (process.argv.length === 2) {
  await writeFile(output, result)
  console.log(`Generated ${output}`)
} else throw new Error('Usage: node scripts/generate-python-bindings.mjs [--check]')
