#!/usr/bin/env python3
"""Embed examples/CustomScripts/*.vsppart into the engine.

OpenVSP only offers a custom component type once its .vsppart file exists in a
"CustomScripts" directory it scans at startup (`Vehicle::m_CustomScriptDirs`).
The browser engine has no such folder, so the files are compiled into the binary
and written into the engine file system before the first scan.

    python3 web/wasm/engine/gen_custom_scripts.py

Writes web/wasm/engine/custom_scripts.inc.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'examples/CustomScripts'
OUT = ROOT / 'web/wasm/engine/custom_scripts.inc'

HEAD = '''// Generated by web/wasm/engine/gen_custom_scripts.py from examples/CustomScripts.
// Do not edit: rerun the generator.

struct EmbeddedScript
{
    const char *name;
    const char *body;
};

static const EmbeddedScript kCustomScripts[] = {
'''


def main():
    files = sorted(SOURCE.glob('*.vsppart'))
    if not files:
        raise SystemExit(f'no .vsppart files under {SOURCE}')
    lines = [HEAD]
    for path in files:
        body = path.read_text()
        lines.append(f'    {{ "{path.name}", {json.dumps(body)} }},')
    lines.append('};')
    lines.append('')
    lines.append(f'static const int kCustomScriptCount = {len(files)};')
    OUT.write_text('\n'.join(lines) + '\n')
    total = sum(path.stat().st_size for path in files)
    print(f'{len(files)} custom scripts embedded ({total} bytes)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
