#!/usr/bin/env python3
"""Generate the enum constants from APIDefines.h for the Python facade.

The desktop package exposes every enum in APIDefines.h through SWIG, so scripts
compare against names like `vsp.ABS_REL_FLAG` or `vsp.VSP_CANT_FIND_PARM`. The
facade is hand-written, so this script keeps the constants in step with the
header instead of listing them by hand.

    python3 web/wasm/engine/gen_enums.py

Writes web/frontend/src/dualWasmProbe/python/enum_table.py.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HEADER = ROOT / 'src/geom_api/APIDefines.h'
OUT = ROOT / 'web/frontend/src/dualWasmProbe/python/enum_table.py'

HEAD = '''"""Generated by web/wasm/engine/gen_enums.py from src/geom_api/APIDefines.h.

Maps every enumerator to its integer value, in declaration order. openvsp_live
injects these as module constants unless the hand-written facade already defines
the name, so generated values never override a checked one.
"""

# name -> int
ENUMS = {
'''


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def parse_enums(text):
    enums = {}
    for match in re.finditer(r'\benum\s+(\w+)\s*\{(.*?)\}', text, re.S):
        name, body = match.group(1), match.group(2)
        values = {}
        current = -1
        for item in body.split(','):
            item = item.strip()
            if not item:
                continue
            if '=' in item:
                label, expr = [part.strip() for part in item.split('=', 1)]
                try:
                    current = eval(expr, {'__builtins__': {}}, dict(values))
                except Exception:
                    continue
            else:
                label = item
                current += 1
            if not re.fullmatch(r'[A-Za-z_]\w*', label):
                continue
            values[label] = int(current)
        enums[name] = values
    return enums


def main():
    text = strip_comments(HEADER.read_text())
    enums = parse_enums(text)
    flat = {}
    duplicates = []
    for enum_name in sorted(enums):
        for label, value in enums[enum_name].items():
            if label in flat and flat[label] != value:
                duplicates.append(label)
            flat.setdefault(label, value)
    lines = [HEAD]
    for label in sorted(flat):
        lines.append(f'    {label!r}: {flat[label]},')
    lines.append('}')
    lines.append('')
    lines.append('# enum name -> its enumerator names, for tooling and tests')
    lines.append('ENUM_GROUPS = {')
    for enum_name in sorted(enums):
        labels = sorted(enums[enum_name])
        lines.append(f'    {enum_name!r}: {labels!r},')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{len(flat)} enumerators in {len(enums)} enums')
    if duplicates:
        print(f'{len(duplicates)} labels repeated with a different value: ' + ', '.join(sorted(set(duplicates))[:8]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
